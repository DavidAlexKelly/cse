function markerSizeForZoom(zoom: number): number {
  if (zoom <= MIN_ZOOM) return MIN_MARKER;
  if (zoom >= MAX_ZOOM_MARKER) return MAX_MARKER;
  const t = (zoom - MIN_ZOOM) / (MAX_ZOOM_MARKER - MIN_ZOOM);
  return Math.round(MIN_MARKER + t * (MAX_MARKER - MIN_MARKER));
}

function buildMarkerSvg(sidc: string, selected: boolean, size: number): string {
  try {
    const sym = new ms.Symbol(sidc, { size, strokeWidth: selected ? 4 : 2 });
    return sym.asSVG();
  } catch {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2 - 2}" fill="#1976d2" stroke="#fff" stroke-width="2"/></svg>`;
  }
}

function computeMarkerOffset(sidc: string, size: number): [number, number] {
  try {
    const sym = new ms.Symbol(sidc, { size });
    const octagon = sym.getOctagonAnchor();
    const bb = sym.getSize();
    const offX = bb.width / 2 - octagon.x;
    const offY = bb.height / 2 - octagon.y;
    return [offX, offY];
  } catch {
    return [0, 0];
  }
}

