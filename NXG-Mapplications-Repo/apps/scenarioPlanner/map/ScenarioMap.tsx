// ── Auto-fit initial view ─────────────────────────────────────────────────
// The map used to always open on a hard-coded Narva coordinate regardless of
// where the scenario's units/orders actually are. Instead, the FIRST time
// there is something on the map to show, compute the smallest lng/lat box
// that contains every unit, arrow endpoint (+ terrain route waypoints) and
// objective, and fit the view to it — falling back to the fixed default only
// for a genuinely empty scenario (a brand-new phase with nothing placed yet).
function computeAutoFitBounds(
  units: PlacedUnit[],
  arrows: PlacedArrow[],
  objectives: PlacedObjective[],
): [[number, number], [number, number]] | null {
  let minLng = Infinity;
  let minLat = Infinity;
  let maxLng = -Infinity;
  let maxLat = -Infinity;
  let found = false;

  const consider = (lng: number, lat: number) => {
    if (!Number.isFinite(lng) || !Number.isFinite(lat)) return;
    found = true;
    if (lng < minLng) minLng = lng;
    if (lng > maxLng) maxLng = lng;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  };

  for (const u of units) consider(u.lng, u.lat);
  for (const a of arrows) {
    consider(a.fromLng, a.fromLat);
    consider(a.toLng, a.toLat);
    // Include the full terrain route so a long movement order isn't clipped
    // by only its two endpoints.
    if (a.routeWaypoints) {
      for (const [lat, lon] of a.routeWaypoints) consider(lon, lat);
    }
  }
  for (const o of objectives) consider(o.lng, o.lat);

  if (!found) return null;
  return [[minLng, minLat], [maxLng, maxLat]];
}

