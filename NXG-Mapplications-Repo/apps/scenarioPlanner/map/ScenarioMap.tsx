function arrowsToGeoJSON(arrows: PlacedArrow[]): GeoJSON.FeatureCollection {
  return {
    type: "FeatureCollection",
    features: arrows.map((a) => ({
      type: "Feature",
      id: a.id,
      properties: {
        colour: a.colour,
        id: a.id,
        lineStyle: a.lineStyle ?? "solid",
        endpointStyle: a.endpointStyle ?? "arrow-filled",
        toLng: a.toLng,
        toLat: a.toLat,
      },
      geometry: {
        type: "LineString",
        coordinates: [
          [a.fromLng, a.fromLat],
          [a.toLng, a.toLat],
        ],
      },
    })),
  };
}

function objectivesToGeoJSON(objectives: PlacedObjective[]): GeoJSON.FeatureCollection {
  return {
    type: "FeatureCollection",
    features: objectives.map((o) => ({
      type: "Feature",
      id: o.id,
      properties: { colour: o.colour, name: o.name, id: o.id },
      geometry: { type: "Point", coordinates: [o.lng, o.lat] },
    })),
  };
}

