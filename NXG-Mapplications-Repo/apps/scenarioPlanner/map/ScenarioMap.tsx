/**
 * Marker inner HTML: the milsymbol SVG plus the ORBAT status badge.
 *
 * IMPORTANT: the badge is anchored to an INNER wrapper, never to the marker
 * element itself. MapLibre owns the marker element's `position` (absolute) and
 * `transform` (the projected screen position) — overriding its position takes
 * the marker out of the map's coordinate space and it drifts on zoom/pan.
 */
function buildMarkerInnerHtml(
  sidc: string,
  selected: boolean,
  size: number,
  showOrbatBadge: boolean,
): string {
  const svg = buildMarkerSvg(sidc, selected, size);
  if (!showOrbatBadge) return svg;
  return (
    `<div style="position:relative;display:inline-block;line-height:0">` +
    svg +
    badgeHtml() +
    `</div>`
  );
}

function makeMarkerEl(
  sidc: string,
  selected: boolean,
  size: number,
  showOrbatBadge: boolean,
): HTMLDivElement {
  const el = document.createElement("div");
  el.style.cursor = "pointer";
  el.style.filter = selected ? "drop-shadow(0 0 4px #2fbf71)" : "none";
  el.dataset.sidc = sidc;
  el.innerHTML = buildMarkerInnerHtml(sidc, selected, size, showOrbatBadge);
  return el;
}

